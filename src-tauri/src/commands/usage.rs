    #[test]
    fn install_and_uninstall_hook_preserves_other_settings() {
        with_temp_home(|home| {
            let claude_dir = home.join(".claude");
            fs::create_dir_all(&claude_dir).unwrap();
            let settings_path = claude_dir.join("settings.json");
            let original = serde_json::json!({
                "model": "kimi-k2",
                "hooks": {
                    "Notification": [{
                        "matcher": "Notification",
                        "hooks": [{"type": "command", "command": "afplay /x.mp3"}]
                    }],
                    "PostToolUse": [{
                        "matcher": "Bash",
                        "hooks": [{"type": "command", "command": "other-script.sh"}]
                    }]
                },
                "permissions": {"defaultMode": "bypassPermissions"}
            });
            fs::write(&settings_path, serde_json::to_string_pretty(&original).unwrap()).unwrap();

            install_usage_hook().expect("install should succeed");

            let after_install: serde_json::Value =
                serde_json::from_str(&fs::read_to_string(&settings_path).unwrap()).unwrap();

            assert_eq!(after_install.get("model").and_then(|m| m.as_str()), Some("kimi-k2"));
            assert_eq!(
                after_install.get("permissions").and_then(|p| p.get("defaultMode")).and_then(|m| m.as_str()),
                Some("bypassPermissions")
            );
            let post = after_install.get("hooks").and_then(|h| h.get("PostToolUse")).unwrap();
            let arr = post.as_array().unwrap();
            assert_eq!(arr.len(), 2, "should have Bash + Skill entries");
            let skill_entry = arr.iter().find(|e| e.get("matcher").and_then(|m| m.as_str()) == Some("Skill"));
            assert!(skill_entry.is_some(), "Skill matcher entry should be added");
            let notif = after_install.get("hooks").and_then(|h| h.get("Notification")).unwrap();
            assert_eq!(notif.as_array().unwrap().len(), 1);

            let script_path = home.join(".skills-manager").join("hooks").join(HOOK_SCRIPT_NAME_UNIX);
            assert!(script_path.exists(), "hook script should exist");
            #[cfg(unix)]
            {
                use std::os::unix::fs::PermissionsExt;
                let perms = fs::metadata(&script_path).unwrap().permissions().mode();
                assert_eq!(perms & 0o111, 0o111, "script should be executable");
            }

            assert_eq!(get_usage_hook_status().unwrap(), true);

            uninstall_usage_hook().expect("uninstall should succeed");
            let after_uninstall: serde_json::Value =
                serde_json::from_str(&fs::read_to_string(&settings_path).unwrap()).unwrap();
            let post = after_uninstall.get("hooks").and_then(|h| h.get("PostToolUse")).unwrap();
            let arr = post.as_array().unwrap();
            assert_eq!(arr.len(), 1, "only Bash entry should remain");
            assert_eq!(
                arr[0].get("matcher").and_then(|m| m.as_str()),
                Some("Bash"),
                "remaining entry should be Bash, not Skill"
            );
            assert_eq!(after_uninstall.get("model").and_then(|m| m.as_str()), Some("kimi-k2"));
            assert!(after_uninstall.get("hooks").and_then(|h| h.get("Notification")).is_some());

            assert_eq!(get_usage_hook_status().unwrap(), false);
        });
    }

